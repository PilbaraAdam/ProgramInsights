-- Control plane 09: Program Insights Private Preview
-- Run once, as SECURITYADMIN (or the owner of PROGRAMINSIGHTS_APP), after 08.
--
-- The Preview is a separate deployment (Preview:Enabled = true) for people with
-- no institution licence: email + generated password, sector benchmarks plus
-- Custom and CGS cluster values, no cost model, no Intelligence.
--
-- Its accounts are Program Insights' own, licensed separately from the
-- Benchmarks Preview, but the table has the same shape and hashing
-- (PBKDF2-HMAC-SHA256, hex, per-row salt and iterations) so Benchmarks'
-- tools/issue_preview_access.py and Key Manager work against it unchanged
-- apart from the table name.
--
-- There is no Entra identity, so every Preview query runs as ONE service
-- account. Snowflake cannot tell Preview users apart, which means the PREVIEW
-- schema has no row access policy: the app's OWNER_KEY = <email> filter is the
-- only isolation between Preview users. Keep that in mind before widening what
-- the Preview stores.

-- ── 1. Accounts ─────────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS PROGRAMINSIGHTS_APP.SECURITY.PREVIEW_USERS (
    EMAIL            VARCHAR       NOT NULL,
    NAME             VARCHAR,
    ORG              VARCHAR,
    PASSWORD_SALT    VARCHAR       NOT NULL,   -- hex
    PASSWORD_HASH    VARCHAR       NOT NULL,   -- hex, PBKDF2-HMAC-SHA256
    HASH_ITERATIONS  NUMBER(38, 0) NOT NULL DEFAULT 240000,
    IS_ACTIVE        BOOLEAN       NOT NULL DEFAULT TRUE,
    CREATED_AT       TIMESTAMP_NTZ NOT NULL DEFAULT CURRENT_TIMESTAMP(),
    -- Sign-in takes the most recent active row per email; move this on reissue.
    UPDATED_AT       TIMESTAMP_NTZ NOT NULL DEFAULT CURRENT_TIMESTAMP(),
    CONSTRAINT PK_PI_PREVIEW_USERS PRIMARY KEY (EMAIL)
);

-- ── 2. Saved work ───────────────────────────────────────────────────────────
CREATE SCHEMA IF NOT EXISTS PROGRAMINSIGHTS_APP.PREVIEW
    COMMENT = 'Program Insights Preview saved work. OWNER_KEY = preview email; app-enforced isolation.';

CREATE TABLE IF NOT EXISTS PROGRAMINSIGHTS_APP.PREVIEW.MODEL            LIKE PILBARA_PRI.PUBLIC.MODEL;
CREATE TABLE IF NOT EXISTS PROGRAMINSIGHTS_APP.PREVIEW.MODEL_CONFIG     LIKE PILBARA_PRI.PUBLIC.MODEL_CONFIG;
CREATE TABLE IF NOT EXISTS PROGRAMINSIGHTS_APP.PREVIEW.PROGRAM          LIKE PILBARA_PRI.PUBLIC.PROGRAM;
CREATE TABLE IF NOT EXISTS PROGRAMINSIGHTS_APP.PREVIEW.PROGRAM_SETTINGS LIKE PILBARA_PRI.PUBLIC.PROGRAM_SETTINGS;
CREATE TABLE IF NOT EXISTS PROGRAMINSIGHTS_APP.PREVIEW.UNITS            LIKE PILBARA_PRI.PUBLIC.UNITS;
CREATE TABLE IF NOT EXISTS PROGRAMINSIGHTS_APP.PREVIEW.PROFILES         LIKE PILBARA_PRI.PUBLIC.PROFILES;

ALTER TABLE PROGRAMINSIGHTS_APP.PREVIEW.MODEL            ADD COLUMN IF NOT EXISTS OWNER_KEY VARCHAR(255);
ALTER TABLE PROGRAMINSIGHTS_APP.PREVIEW.MODEL_CONFIG     ADD COLUMN IF NOT EXISTS OWNER_KEY VARCHAR(255);
ALTER TABLE PROGRAMINSIGHTS_APP.PREVIEW.PROGRAM          ADD COLUMN IF NOT EXISTS OWNER_KEY VARCHAR(255);
ALTER TABLE PROGRAMINSIGHTS_APP.PREVIEW.PROGRAM_SETTINGS ADD COLUMN IF NOT EXISTS OWNER_KEY VARCHAR(255);
ALTER TABLE PROGRAMINSIGHTS_APP.PREVIEW.UNITS            ADD COLUMN IF NOT EXISTS OWNER_KEY VARCHAR(255);
ALTER TABLE PROGRAMINSIGHTS_APP.PREVIEW.PROFILES         ADD COLUMN IF NOT EXISTS OWNER_KEY VARCHAR(255);

-- ── 3. Service role and user ────────────────────────────────────────────────
CREATE ROLE IF NOT EXISTS PROGRAMINSIGHTS_PREVIEW
    COMMENT = 'Program Insights Preview service role: read sector data, read PREVIEW_USERS, read/write PREVIEW schema.';

GRANT USAGE ON WAREHOUSE COMPUTE_WH TO ROLE PROGRAMINSIGHTS_PREVIEW;

GRANT USAGE  ON DATABASE PROGRAMINSIGHTS_APP                        TO ROLE PROGRAMINSIGHTS_PREVIEW;
-- Schema USAGE is the grant that gets forgotten: without it PREVIEW_USERS is
-- invisible and every sign-in fails as though the password were wrong.
GRANT USAGE  ON SCHEMA   PROGRAMINSIGHTS_APP.SECURITY               TO ROLE PROGRAMINSIGHTS_PREVIEW;
GRANT SELECT ON TABLE    PROGRAMINSIGHTS_APP.SECURITY.PREVIEW_USERS TO ROLE PROGRAMINSIGHTS_PREVIEW;   -- read only: issuing access stays an admin act

GRANT USAGE ON SCHEMA PROGRAMINSIGHTS_APP.PREVIEW TO ROLE PROGRAMINSIGHTS_PREVIEW;
GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE PROGRAMINSIGHTS_APP.PREVIEW.MODEL            TO ROLE PROGRAMINSIGHTS_PREVIEW;
GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE PROGRAMINSIGHTS_APP.PREVIEW.MODEL_CONFIG     TO ROLE PROGRAMINSIGHTS_PREVIEW;
GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE PROGRAMINSIGHTS_APP.PREVIEW.PROGRAM          TO ROLE PROGRAMINSIGHTS_PREVIEW;
GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE PROGRAMINSIGHTS_APP.PREVIEW.PROGRAM_SETTINGS TO ROLE PROGRAMINSIGHTS_PREVIEW;
GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE PROGRAMINSIGHTS_APP.PREVIEW.UNITS            TO ROLE PROGRAMINSIGHTS_PREVIEW;
GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE PROGRAMINSIGHTS_APP.PREVIEW.PROFILES         TO ROLE PROGRAMINSIGHTS_PREVIEW;

GRANT USAGE  ON DATABASE AU_HIGHER_ED_FUNDING                          TO ROLE PROGRAMINSIGHTS_PREVIEW;
GRANT USAGE  ON SCHEMA   AU_HIGHER_ED_FUNDING.CURATED                  TO ROLE PROGRAMINSIGHTS_PREVIEW;
GRANT SELECT ON TABLE    AU_HIGHER_ED_FUNDING.CURATED.HELP_ALLOCATIONS TO ROLE PROGRAMINSIGHTS_PREVIEW;
GRANT USAGE  ON DATABASE BENCHMARK_APP                                 TO ROLE PROGRAMINSIGHTS_PREVIEW;
GRANT USAGE  ON SCHEMA   BENCHMARK_APP.CLIENT                          TO ROLE PROGRAMINSIGHTS_PREVIEW;
