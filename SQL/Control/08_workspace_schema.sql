-- Control plane 08: WORKSPACE — saved work for Program Insights members
-- Run once, as SECURITYADMIN (or the owner of PROGRAMINSIGHTS_APP), after 07.
--
-- Members have no client database, so their scenarios and programs are saved
-- here, in one shared schema, with an OWNER_KEY column holding their
-- institution's MODEL key. Existing clients keep saving in their own databases.
--
-- Same six tables as a client database, cloned by structure from PILBARA_PRI
-- (as 06 does), so every unqualified app query ("FROM PROGRAM") works unchanged
-- once the connection's database/schema is set to PROGRAMINSIGHTS_APP.WORKSPACE.
--
-- Isolation: the app writes and filters OWNER_KEY, AND a row access policy
-- enforces it in Snowflake, so one institution's rows are invisible to another
-- even through a direct query. Row access policies do not apply to INSERT; a
-- row written with someone else's key simply becomes invisible to its writer.

CREATE SCHEMA IF NOT EXISTS PROGRAMINSIGHTS_APP.WORKSPACE
    COMMENT = 'Program Insights saved work for members (no client database).';

CREATE TABLE IF NOT EXISTS PROGRAMINSIGHTS_APP.WORKSPACE.MODEL            LIKE PILBARA_PRI.PUBLIC.MODEL;
CREATE TABLE IF NOT EXISTS PROGRAMINSIGHTS_APP.WORKSPACE.MODEL_CONFIG     LIKE PILBARA_PRI.PUBLIC.MODEL_CONFIG;
CREATE TABLE IF NOT EXISTS PROGRAMINSIGHTS_APP.WORKSPACE.PROGRAM          LIKE PILBARA_PRI.PUBLIC.PROGRAM;
CREATE TABLE IF NOT EXISTS PROGRAMINSIGHTS_APP.WORKSPACE.PROGRAM_SETTINGS LIKE PILBARA_PRI.PUBLIC.PROGRAM_SETTINGS;
CREATE TABLE IF NOT EXISTS PROGRAMINSIGHTS_APP.WORKSPACE.UNITS            LIKE PILBARA_PRI.PUBLIC.UNITS;
CREATE TABLE IF NOT EXISTS PROGRAMINSIGHTS_APP.WORKSPACE.PROFILES         LIKE PILBARA_PRI.PUBLIC.PROFILES;

ALTER TABLE PROGRAMINSIGHTS_APP.WORKSPACE.MODEL            ADD COLUMN IF NOT EXISTS OWNER_KEY VARCHAR(255);
ALTER TABLE PROGRAMINSIGHTS_APP.WORKSPACE.MODEL_CONFIG     ADD COLUMN IF NOT EXISTS OWNER_KEY VARCHAR(255);
ALTER TABLE PROGRAMINSIGHTS_APP.WORKSPACE.PROGRAM          ADD COLUMN IF NOT EXISTS OWNER_KEY VARCHAR(255);
ALTER TABLE PROGRAMINSIGHTS_APP.WORKSPACE.PROGRAM_SETTINGS ADD COLUMN IF NOT EXISTS OWNER_KEY VARCHAR(255);
ALTER TABLE PROGRAMINSIGHTS_APP.WORKSPACE.UNITS            ADD COLUMN IF NOT EXISTS OWNER_KEY VARCHAR(255);
ALTER TABLE PROGRAMINSIGHTS_APP.WORKSPACE.PROFILES         ADD COLUMN IF NOT EXISTS OWNER_KEY VARCHAR(255);

-- ── Row access policy ───────────────────────────────────────────────────────
-- A row is visible when its OWNER_KEY is the institution of the session's
-- active role. The policy body runs with the policy owner's rights, so members
-- need no SELECT on ROLE_MODEL_MAP. Program Insights admins see everything so
-- support can investigate.
CREATE ROW ACCESS POLICY IF NOT EXISTS PROGRAMINSIGHTS_APP.SECURITY.WORKSPACE_OWNER_RLS
    AS (OWNER_KEY VARCHAR) RETURNS BOOLEAN ->
    IS_ROLE_IN_SESSION('SECURITYADMIN')
    OR EXISTS (
        SELECT 1
        FROM PROGRAMINSIGHTS_APP.SECURITY.ROLE_MODEL_MAP m
        WHERE m.IS_ACTIVE
          AND UPPER(TRIM(m.ROLE_NAME)) = UPPER(TRIM(CURRENT_ROLE()))
          AND m.MODEL = OWNER_KEY
    );

ALTER TABLE PROGRAMINSIGHTS_APP.WORKSPACE.MODEL            ADD ROW ACCESS POLICY PROGRAMINSIGHTS_APP.SECURITY.WORKSPACE_OWNER_RLS ON (OWNER_KEY);
ALTER TABLE PROGRAMINSIGHTS_APP.WORKSPACE.MODEL_CONFIG     ADD ROW ACCESS POLICY PROGRAMINSIGHTS_APP.SECURITY.WORKSPACE_OWNER_RLS ON (OWNER_KEY);
ALTER TABLE PROGRAMINSIGHTS_APP.WORKSPACE.PROGRAM          ADD ROW ACCESS POLICY PROGRAMINSIGHTS_APP.SECURITY.WORKSPACE_OWNER_RLS ON (OWNER_KEY);
ALTER TABLE PROGRAMINSIGHTS_APP.WORKSPACE.PROGRAM_SETTINGS ADD ROW ACCESS POLICY PROGRAMINSIGHTS_APP.SECURITY.WORKSPACE_OWNER_RLS ON (OWNER_KEY);
ALTER TABLE PROGRAMINSIGHTS_APP.WORKSPACE.UNITS            ADD ROW ACCESS POLICY PROGRAMINSIGHTS_APP.SECURITY.WORKSPACE_OWNER_RLS ON (OWNER_KEY);
ALTER TABLE PROGRAMINSIGHTS_APP.WORKSPACE.PROFILES         ADD ROW ACCESS POLICY PROGRAMINSIGHTS_APP.SECURITY.WORKSPACE_OWNER_RLS ON (OWNER_KEY);

-- ── One grant bundle, granted to every member role (07 §d) ──────────────────
CREATE ROLE IF NOT EXISTS PROGRAMINSIGHTS_WORKSPACE_USER
    COMMENT = 'Read/write on PROGRAMINSIGHTS_APP.WORKSPACE. Rows are scoped by WORKSPACE_OWNER_RLS.';

GRANT USAGE ON DATABASE PROGRAMINSIGHTS_APP           TO ROLE PROGRAMINSIGHTS_WORKSPACE_USER;
GRANT USAGE ON SCHEMA   PROGRAMINSIGHTS_APP.WORKSPACE TO ROLE PROGRAMINSIGHTS_WORKSPACE_USER;
GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE PROGRAMINSIGHTS_APP.WORKSPACE.MODEL            TO ROLE PROGRAMINSIGHTS_WORKSPACE_USER;
GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE PROGRAMINSIGHTS_APP.WORKSPACE.MODEL_CONFIG     TO ROLE PROGRAMINSIGHTS_WORKSPACE_USER;
GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE PROGRAMINSIGHTS_APP.WORKSPACE.PROGRAM          TO ROLE PROGRAMINSIGHTS_WORKSPACE_USER;
GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE PROGRAMINSIGHTS_APP.WORKSPACE.PROGRAM_SETTINGS TO ROLE PROGRAMINSIGHTS_WORKSPACE_USER;
GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE PROGRAMINSIGHTS_APP.WORKSPACE.UNITS            TO ROLE PROGRAMINSIGHTS_WORKSPACE_USER;
GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE PROGRAMINSIGHTS_APP.WORKSPACE.PROFILES         TO ROLE PROGRAMINSIGHTS_WORKSPACE_USER;

